def convert_sales_volume(value):
    if pd.isna(value):
        return np.nan

    value = str(value).lower().replace(',', '').strip()

    match = re.search(r'(\d+(?:\.\d+)?)\s*(k)?', value)

    if match is None:
        return np.nan

    number = pd.to_numeric(match.group(1), errors='coerce')

    if pd.isna(number):
        return np.nan

    if match.group(2) == 'k':
        number *= 1000

    return number


