# 4. CUSTOMER FEEDBACK SEGMENT
# Combine rating and review volume

rating = df_clean['product_star_rating']
reviews = df_clean['product_num_ratings']

valid_feedback = rating.notna() & reviews.notna()

high_rating = rating >= 4
high_reviews = reviews >= 1000

df_clean['customer_feedback_segment'] = np.select(
    [
        valid_feedback & high_rating & high_reviews,

        valid_feedback & high_rating & ~high_reviews,

        valid_feedback & ~high_rating & high_reviews,

        valid_feedback & ~high_rating & ~high_reviews
    ],
    [
        'High Rating + High Reviews',
        'High Rating + Low/Medium Reviews',
        'Lower Rating + High Reviews',
        'Lower Rating + Low/Medium Reviews'
    ],
    default=None
)


